#!/usr/bin/env node
// Builds chrome/lib/psl-data.js from the Public Suffix List
// (https://publicsuffix.org/list/public_suffix_list.dat, MPL-2.0).
//
//   curl -sSLo public_suffix_list.dat https://publicsuffix.org/list/public_suffix_list.dat
//   node tools/build-psl.js public_suffix_list.dat
//   node tools/sync-shared.js
//
// Rules are kept as-is except that internationalized labels are converted
// to their ASCII (punycode) form, because that is what URL.hostname gives
// us at runtime. Both the ICANN and the PRIVATE sections are included: the
// private one is what separates e.g. alice.github.io from bob.github.io.
const fs = require('fs');
const path = require('path');
const { domainToASCII } = require('url');

const src = process.argv[2];
if (!src) {
  console.error('usage: node tools/build-psl.js <public_suffix_list.dat>');
  process.exit(1);
}

const rules = new Set();
for (const raw of fs.readFileSync(src, 'utf8').split(/\r?\n/)) {
  const line = raw.trim().split(/\s/)[0];
  if (!line || line.startsWith('//')) continue;
  let prefix = '';
  let body = line;
  if (body.startsWith('!')) {
    prefix = '!';
    body = body.slice(1);
  }
  let wildcard = '';
  if (body.startsWith('*.')) {
    wildcard = '*.';
    body = body.slice(2);
  }
  const ascii = domainToASCII(body);
  if (!ascii) {
    console.warn('skipping unconvertible rule:', line);
    continue;
  }
  rules.add(prefix + wildcard + ascii.toLowerCase());
}

const list = [...rules].sort();
const out =
  '// Generated by tools/build-psl.js from the Public Suffix List\n' +
  '// (https://publicsuffix.org/list/, Mozilla Public License 2.0). Do not edit by hand.\n' +
  `// ${list.length} rules.\n` +
  `globalThis.KASA_PSL = ${JSON.stringify(list.join('\n'))};\n`;

const dest = path.join(__dirname, '..', 'chrome', 'lib', 'psl-data.js');
fs.writeFileSync(dest, out);
console.log(`wrote ${dest} (${list.length} rules, ${out.length} bytes)`);
